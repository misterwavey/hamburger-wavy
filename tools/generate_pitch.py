"""Generate project chromatic dividers; no vendor data inputs.

49 notes, +7 through -41 semitones. Each integer is nearest to
native_divider * 2**(-semitones/12), ties rounded upward.
Native dividers are the existing board's nominal clock anchors, not
measured calibration values. RODIV + ROTRIM/512 is encoded as divider/512.
"""
from decimal import Decimal, localcontext, ROUND_HALF_UP
from pathlib import Path
import argparse
import json

RATES = (44100, 48000, 88200, 96000)
BASES = (2176, 2000, 1088, 1000)
NOTES = tuple(range(7, -42, -1))

def generate(output):
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    errors = []
    with localcontext() as ctx:
        ctx.prec = 60
        for base in BASES:
            row = []
            for note in NOTES:
                ideal = Decimal(base) * Decimal(2) ** (-Decimal(note) / 12)
                value = int(ideal.to_integral_value(rounding=ROUND_HALF_UP))
                if not 512 <= value <= min(65535, 32767 * 512 + 511):
                    raise ValueError('divider outside fractional clock range')
                row.append(value)
                cents = 1200 * (ideal / Decimal(value)).ln() / Decimal(2).ln()
                errors.append(abs(cents))
            rows.append(row)
    header = ['/* Generated by tools/generate_pitch.py; do not edit. */',
              '#ifndef ONE_PITCH_TABLES_H', '#define ONE_PITCH_TABLES_H',
              'static const uint16_t chromatic_dividers[4][49] = {']
    for row in rows:
        header.append('  {' + ', '.join(map(str, row)) + '},')
    header.extend(['};', '#endif', ''])
    (output / 'pitch_tables.h').write_text('\n'.join(header))
    report = dict(rates=list(RATES), native_dividers=list(BASES),
                  semitones=list(NOTES), dividers=rows,
                  mapping='n = 7 - floor((clamp(value,0,255)*48 + 127)/255)',
                  rounding='nearest integer; half upward; Decimal precision 60',
                  max_rounding_error_cents=float(max(errors)),
                  calibration='relative to nominal board native anchors; not measured absolute tuning or V/oct')
    (output / 'pitch_tables.json').write_text(json.dumps(report, indent=2) + '\n')
    return report

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, default=Path('build/pitch'))
    print(json.dumps(generate(parser.parse_args().out), indent=2))
